/**
 * Calculates event counts per category
 */
export function calculateCategoryCounts(events = INITIAL_AUDIT_LOGS_EXPANDED) {
  const counts = {
    "All Events": events.length,
    Security: 0,
    Users: 0,
    Payments: 0,
    Jobs: 0,
    "Job Sources": 0,
    Administration: 0,
    System: 0,
  };

  events.forEach((e) => {
    if (counts[e.category] !== undefined) {
      counts[e.category] += 1;
    }
  });

  return counts;
}

